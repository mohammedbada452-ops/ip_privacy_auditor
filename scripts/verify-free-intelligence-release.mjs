import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const failures = [];
const must = (condition, message) => { if (!condition) failures.push(message); };

must(read('server/services/rdap.ts').includes("https://rdap.org/ip/"), 'RDAP free service missing.');
must(read('server/services/reverseDns.ts').includes('https://cloudflare-dns.com/dns-query'), 'Cloudflare DoH reverse DNS missing.');
must(read('server/providers/geoip/IpInfoLiteProvider.ts').includes('https://api.ipinfo.io/lite'), 'IPinfo Lite provider missing.');
must(read('server/services/geoip.ts').includes("case 'ipinfo-lite'"), 'IPinfo Lite provider selector missing.');
must(read('server/providers/geoip/CloudflareRequestCfProvider.ts').includes('request.cf metadata is unavailable'), 'Cloudflare request.cf provider must fail closed when edge metadata is absent.');
must(read('server/providers/geoip/HackMyIPProvider.ts').includes('returned data for a different IP address'), 'HackMyIP response IP binding validation missing.');
must(read('server/providers/geoip/IpInfoLiteProvider.ts').includes('returned data for a different IP address'), 'IPinfo Lite response IP binding validation missing.');
must(read('server/services/geoip.ts').includes('Mock GeoIP provider is disabled outside test/development'), 'Production must explicitly block mock GeoIP.');
must(read('src/features/browser/collectors/timezoneCollector.ts').includes('Browser did not expose a timezone identifier.'), 'Timezone collector must not fabricate UTC when unavailable.');
must(read('src/features/ip/components/NetworkIntelligenceCard.tsx').includes('IPinfo Lite attribution'), 'IPinfo Lite attribution missing.');
must(!fs.existsSync(path.join(root, 'node_modules')), 'node_modules must not be shipped in release.');
must(!fs.existsSync(path.join(root, 'dist')), 'dist must be generated by Cloudflare and not shipped in release.');
must(fs.existsSync(path.join(root, 'package-lock.json')), 'package-lock.json must be present.');
must(!fs.existsSync(path.join(root, 'bun.lock')), 'bun.lock must not be present.');
const sitemapPath = path.join(root, 'public', 'sitemap.xml');
if (fs.existsSync(sitemapPath)) {
  const sitemap = fs.readFileSync(sitemapPath, 'utf8');
  must(!sitemap.includes('YOUR_PRODUCTION_DOMAIN'), 'sitemap.xml must not contain a placeholder production domain.');
}

if (failures.length) {
  console.error('FREE INTELLIGENCE RELEASE: FAIL');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}
console.log('FREE INTELLIGENCE RELEASE: PASS');
